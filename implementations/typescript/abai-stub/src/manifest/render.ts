// Rendering the manifest as abaigram.yaml and reading it back.
//
// The rendering must be byte-stable across machines and Node versions, since
// `<entry> doctor` and the self-check test compare the checked-in file with
// the rendered manifest: keys keep their insertion order, lines are never
// folded, the header carries no version or date, and strings a YAML 1.1
// reader would take for booleans are quoted.
import { Document, parse, Scalar, visit } from "yaml";
import type { Manifest } from "./manifest.ts";

/** The comment above the rendered manifest, computed from its name, grammar version and entry. */
function header(manifest: Manifest): string {
	const entry = manifest.entry;
	return [
		` abaigram.yaml: the manifest of ${manifest.name} as an abaigram (abaigrammar ${manifest.abaigrammar}).`,
		` Generated by \`${entry} manifest\` from the program's declarations in code.`,
		` Do not edit by hand: \`${entry} doctor\` and the test suite check that this file`,
		` agrees with the code. Regenerate with \`${entry} manifest > abaigram.yaml\`.`,
	].join("\n");
}

/** Strings YAML 1.2 renders bare but a YAML 1.1 reader (PyYAML, go-yaml v2) takes for booleans. */
const YAML_1_1_BOOLEANS = /^(?:y|yes|n|no|on|off)$/i;

/** Render the manifest as YAML text with exactly one trailing newline. */
export function renderManifestYaml(manifest: Manifest): string {
	const doc = new Document(manifest);
	doc.commentBefore = header(manifest);
	visit(doc, {
		Scalar(_key, node) {
			if (typeof node.value === "string" && YAML_1_1_BOOLEANS.test(node.value)) {
				node.type = Scalar.QUOTE_DOUBLE;
			}
		},
	});
	const text = doc.toString({ lineWidth: 0 });
	return `${text.replace(/\n+$/, "")}\n`;
}

/** Parse YAML text into a plain value; the caller validates it. */
export function parseManifestYaml(text: string): unknown {
	return parse(text);
}

/** A callsign no live session has; the random source is injectable for tests. */
export function pickCallsign(taken: ReadonlySet<string>, random: () => number = Math.random): string {
	for (let attempt = 0; attempt < 200; attempt++) {
		const a = FIRST[Math.floor(random() * FIRST.length)];
		const b = SECOND[Math.floor(random() * SECOND.length)];
		const name = `${a}-${b}`;
		if (!taken.has(name)) return name;
	}
	throw new Error("no callsign left");
}

export const CALLSIGN_COUNT = FIRST.length * SECOND.length;
